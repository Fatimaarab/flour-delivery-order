/**
 * ساخت خودکار فایل تنظیمات با یک کلید امن.
 *
 * این اسکریپت همان دامی را می‌بندد که در تست پذیرش گرفتار شد: کپی کردن
 * فایل نمونه و جا ماندن مقدار `change-me`. اینجا کلید همان لحظه ساخته
 * می‌شود و کاربر هیچ کار دستی‌ای لازم ندارد.
 *
 * اگر فایل .env از قبل وجود داشته باشد، **دست نمی‌خورد** — تا اجرای دوباره
 * نصب، تنظیمات موجود را خراب نکند.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const ENV_PATH = '.env';

if (existsSync(ENV_PATH)) {
  console.log('فایل تنظیمات (.env) از قبل وجود دارد — دست نخورد.');
  process.exit(0);
}

const secret = randomBytes(48).toString('base64url');

const content = `# تنظیمات سامانه حواله آرد
# این فایل به‌صورت خودکار ساخته شده است.

# مسیر فایل دیتابیس (بکاپ = کپی همین یک فایل)
DATABASE_URL="file:./data/ard.db"

# کلید امضای نشست کاربران و کد QR روی برگه‌های حواله.
# به‌صورت تصادفی ساخته شده — آن را عوض نکنید و به کسی ندهید.
JWT_SECRET="${secret}"

# پورت سرور
PORT=4000

# پوشه بکاپ‌ها — روی سرور واقعی، بهتر است درایو دیگری باشد
BACKUP_DIR="backups"

# چند نسخه بکاپ نگه داشته شود
BACKUP_KEEP=30

# نسخه دوم بکاپ — پوشه‌ای روی کامپیوتر یا دیسک دیگر (مثلاً \\\\PC2\\ArdBackup یا E:\\ArdBackup).
# اگر خالی باشد، بکاپ فقط روی همین سرور می‌ماند و با خرابی دیسک از بین می‌رود.
BACKUP_COPY_DIR=""

# پیامک: off = خاموش، test = آزمایشی (ثبت می‌شود ولی فرستاده نمی‌شود)
SMS_PROVIDER="off"
# شماره موبایل مدیر یا مدیران کارخانه؛ با ویرگول جدا کنید
SMS_MANAGER_NUMBERS=""
`;

writeFileSync(ENV_PATH, content, 'utf8');
console.log('فایل تنظیمات (.env) ساخته شد و کلید امن تولید گردید.');
